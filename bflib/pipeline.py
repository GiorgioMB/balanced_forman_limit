"""Execution machinery shared by all experiments.

Every simulation is split into small deterministic tasks. A task's result is written atomically to
its own file under results/<scale>/raw/, so an interrupted run resumes where it stopped and a
finished task is never recomputed. Analysis steps only read these files.
"""

import json
import multiprocessing as mp
import os
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent


# ------------------------------------------------------------------------------- context
@dataclass
class Context:
    scale: str
    root: Path
    jobs: int = 1
    report: list = field(default_factory=list)

    def __post_init__(self):
        self.root = Path(self.root)
        for sub in ("raw", "summaries", "tables", "figures"):
            (self.root / sub).mkdir(parents=True, exist_ok=True)
        # results are never version-controlled, wherever --results points
        ignore = self.root.parent / ".gitignore"
        if not ignore.exists():
            ignore.write_text("# written by reproduce.py: results are not version-controlled\n*\n")

    @property
    def paper(self):
        return self.scale == "paper"

    def raw(self, *parts):
        path = self.root.joinpath("raw", *parts)
        path.parent.mkdir(parents=True, exist_ok=True)
        return path

    def summary_path(self, name):
        return self.root / "summaries" / f"{name}.json"

    def save_summary(self, name, obj):
        with open(self.summary_path(name), "w") as fh:
            json.dump(obj, fh, indent=1, default=_json_default)

    def load_summary(self, name):
        path = self.summary_path(name)
        if not path.exists():
            raise FileNotFoundError(f"{path} is missing: run the experiment that produces it first")
        with open(path) as fh:
            return json.load(fh)

    def write_table(self, name, caption, rows):
        """Write the body rows of a manuscript table (to paste between \\midrule and \\bottomrule)."""
        path = self.root / "tables" / f"{name}.tex"
        with open(path, "w") as fh:
            fh.write(f"% {caption}\n% generated by reproduce.py (scale: {self.scale})\n")
            for row in rows:
                fh.write(row + "\n")
        return path

    def figure(self, name):
        return self.root / "figures" / name

    def note(self, line=""):
        self.report.append(line)


def _json_default(obj):
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return float(obj)
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    raise TypeError(type(obj))


# ------------------------------------------------------------------------------- tasks
@dataclass
class Task:
    out: Path
    fn: object
    args: tuple

    def done(self):
        return Path(self.out).exists()


def _execute(task):
    result = task.fn(*task.args)
    out = Path(task.out)
    tmp = out.with_name(out.name + f".tmp{os.getpid()}")
    if out.suffix == ".npy":
        with open(tmp, "wb") as fh:
            np.save(fh, np.asarray(result))
    elif out.suffix == ".npz":
        with open(tmp, "wb") as fh:
            np.savez_compressed(fh, **result)
    elif out.suffix == ".json":
        with open(tmp, "w") as fh:
            json.dump(result, fh, default=_json_default)
    else:
        with open(tmp, "wb") as fh:
            fh.write(result)
    os.replace(tmp, out)
    return str(out)


def run_tasks(ctx, label, tasks):
    """Run the tasks that have no output file yet, with ctx.jobs worker processes."""
    pending = [t for t in tasks if not t.done()]
    if not pending:
        print(f"  [{label}] {len(tasks)} tasks already done", flush=True)
        return
    print(f"  [{label}] running {len(pending)} of {len(tasks)} tasks with {ctx.jobs} worker(s)", flush=True)
    start, last = time.time(), 0.0
    # tasks always run in worker processes, recycled regularly, so that memory is returned to the system
    # and --jobs 1 behaves like any other value
    pool = mp.get_context("spawn").Pool(min(ctx.jobs, len(pending)), maxtasksperchild=25)
    try:
        for count, _ in enumerate(pool.imap_unordered(_execute, pending, chunksize=1), 1):
            now = time.time() - start
            if now - last > 30 or count == len(pending):
                eta = now / count * (len(pending) - count)
                print(f"  [{label}] {count}/{len(pending)} done, {now:.0f} s elapsed, ~{eta:.0f} s left", flush=True)
                last = now
    finally:
        pool.close()
        pool.join()


# ------------------------------------------------------------------------------- native code
BUILD = REPO / "build"
_PROGRAMS = {"bfgraph": "bfgraph.c", "kernel": "kernel.c"}


def native(program):
    """Path of a compiled C program; compiles it on first use (or when the source changed)."""
    source = REPO / "csrc" / _PROGRAMS[program]
    binary = BUILD / program
    if binary.exists() and binary.stat().st_mtime >= max(source.stat().st_mtime,
                                                          (REPO / "csrc" / "bfcommon.h").stat().st_mtime):
        return binary
    BUILD.mkdir(exist_ok=True)
    compiler = os.environ.get("CC") or shutil.which("cc") or shutil.which("gcc") or shutil.which("clang")
    if compiler is None:
        sys.exit("A C compiler is required (set CC, or install cc/gcc/clang).")
    for flags in (["-O3", "-march=native"], ["-O3"]):
        cmd = [compiler, *flags, "-o", str(binary), str(source), "-lm"]
        if subprocess.run(cmd, capture_output=True).returncode == 0:
            return binary
    raise RuntimeError("compilation failed: " + " ".join(cmd))


def bfgraph_edges(d, n, lam, seed):
    """Per-edge records (t, BF, S) of the binomial RGG on T^d (C program bfgraph, mode edges)."""
    out = BUILD / f"tmp_edges_{os.getpid()}_{d}_{n}_{lam}_{seed}.bin"
    subprocess.run([str(native("bfgraph")), "edges", str(d), str(n), repr(lam), str(seed), str(out)],
                   check=True, capture_output=True)
    data = np.fromfile(out, dtype=np.float32).reshape(-1, 3)
    out.unlink()
    return data


def bfgraph_binned(space, n0, param, rmode, seed0, n_graphs, n_bins=100):
    """Per-graph binned sums from bfgraph (mode binned): array (graphs, 3 + 4 n_bins) with columns
    seed, N, E, then (count, sum BF, sum kink, sum Psi_2) for each bin of t."""
    proc = subprocess.run([str(native("bfgraph")), "binned", space, repr(float(n0)), repr(float(param)), rmode,
                           str(seed0), str(n_graphs), str(n_bins)], check=True, capture_output=True, text=True)
    return np.loadtxt(proc.stdout.splitlines(), ndmin=2)


def kernel_samples(lam, eps, seed0, n_samples):
    """Rows (seed, total, S, J) of the second-order kernel program."""
    proc = subprocess.run([str(native("kernel")), repr(float(lam)), repr(float(eps)), str(seed0), str(n_samples)],
                          check=True, capture_output=True, text=True)
    return np.loadtxt(proc.stdout.splitlines(), ndmin=2)


# ------------------------------------------------------------------------------- figures
def figure_style():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({
        "font.family": "serif", "mathtext.fontset": "cm", "font.size": 9, "axes.labelsize": 9,
        "legend.fontsize": 7.5, "xtick.labelsize": 8, "ytick.labelsize": 8, "axes.linewidth": 0.6,
        "lines.linewidth": 1.0,
    })
    return plt


def plain_log_ticks(axis, values):
    """Ticks at the given values of a logarithmic axis, labelled plainly; minor ticks are not labelled
    (matplotlib labels them when an axis spans less than a decade, and the labels then overlap)."""
    from matplotlib.ticker import FixedFormatter, FixedLocator, NullFormatter

    axis.set_major_locator(FixedLocator(values))
    axis.set_major_formatter(FixedFormatter([f"{v:g}" for v in values]))
    axis.set_minor_formatter(NullFormatter())


def fmt_pm(value, se, digits=5):
    return f"{value:+.{digits}f}\\,$\\pm$\\,{se:.{digits}f}"
